import assert from 'node:assert/strict';
import {mountLocalFile,createLocalLoader} from '../deps/wasm/local-files.mjs';
const nodes=new Map();
const FS={mkdirTree(){},createDataFile(dir,name){nodes.set(dir+'/'+name,{node_ops:{getattr:()=>({mode:1,size:0})},stream_ops:{}})},lookupPath:path=>({node:nodes.get(path)}),ErrnoError:Error};
const Module={Asyncify:{handleAsync:fn=>fn()}};
const reads=[];
const file={name:'reads.bam',size:10**10,slice(start,end){reads.push([start,end]);return {async arrayBuffer(){return new Uint8Array(end-start).fill(7).buffer;}}},arrayBuffer(){throw new Error('Whole-file reads forbidden');}};
const path=mountLocalFile(FS,Module,'/x','reads.bam',file),node=nodes.get(path);
assert.equal(node.node_ops.getattr(node).size,10**10);
const bytes=new Uint8Array(16);
assert.equal(await node.stream_ops.read({},bytes,3,5,123456789),5);
assert.deepEqual(reads,[[123456789,123456794]]);assert.equal(bytes[3],7);
assert.equal(node.stream_ops.llseek({position:12},-2,1),10);
assert.equal(node.stream_ops.llseek({},-1,2),file.size-1);
assert.equal(await node.stream_ops.read({},bytes,0,5,file.size),0);
assert.throws(()=>mountLocalFile(FS,{},'/x','other',file),/Asyncify/);
const commands=[],messages=[];
const loader=createLocalLoader({FS,Module,command:async text=>commands.push(text),status:text=>messages.push(text)});
await loader.accept([file]);assert.equal(commands.length,0);assert.match(messages.at(-1),/Waiting for index/);
const index={...file,name:'reads.bai',size:100};
await loader.accept([index]);assert.equal(commands.length,1);assert.match(commands[0],/^load \/local\/1\/reads.bam$/);
assert.ok(nodes.has('/local/1/reads.bam.bai'));
await loader.accept([file,index]);assert.match(commands[1],/\/local\/2\/reads.bam$/);
assert.equal(reads.length,1,'Mounting must not read/upload BAM contents');
console.log('PASS: local 10 GB File uses bounded range reads; index waiting, alternate index names and reload');

const vcf={...file,name:'calls.vcf',size:300};
await loader.accept([vcf],{track:true,tiles:true});
assert.match(commands.at(-2),/^load tiled .*calls.vcf$/);
assert.match(commands.at(-1),/^load track .*calls.vcf$/);
await loader.accept([vcf],{track:false,tiles:true});
assert.match(commands.at(-1),/^load tiled .*calls.vcf$/);
console.log('PASS: local VCF can open as a track, tiles, or both');
